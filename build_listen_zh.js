// sanity check
let days = Object.keys(EN_PRACTICE).length;
let ok = true;
Object.keys(EN_PRACTICE).forEach(k=>{
  const n = EN_PRACTICE[k].lines.length;
  if (!ZH[k] || ZH[k].length !== n) { ok=false; console.error('MISMATCH day', k, 'lines', n, 'zh', ZH[k]?ZH[k].length:0); }
});
if(!ok){ process.exit(1); }

const jq = s => JSON.stringify(s);
const out = [];
out.push('/* =========================================================');
out.push('   旺仔的工作台 · 英语学习「听 / 说 / 单词」交互训练数据');
out.push('   与 content.js 中 english 数组一一对应（索引 0-20）。');
out.push('   每条：');
out.push('     lines    听力对话 10 句（role + en + zh 中文翻译）');
out.push('     speak    口语跟读 3 个目标句（数组）');
out.push('     words    单词卡 12-15 个（w + ph + zh）');
out.push('   说明：本文件不依赖任何外部库，配合 index.html 的 Web Speech API 使用。');
out.push('   ========================================================= */');
out.push('const EN_PRACTICE = {');
Object.keys(EN_PRACTICE).forEach((k)=>{
  const d = EN_PRACTICE[k];
  out.push('  ' + k + ': {');
  out.push('    lines: [');
  d.lines.forEach((l, i)=>{
    out.push('      {role:' + jq(l.role) + ', en:' + jq(l.en) + ', zh:' + jq(ZH[k][i]) + '},');
  });
  out.push('    ],');
  out.push('    speak: [' + d.speak.map(s=>jq(s)).join(', ') + '],');
  out.push('    words: [');
  d.words.forEach(w=>{
    out.push('      {w:' + jq(w.w) + ', ph:' + jq(w.ph) + ', zh:' + jq(w.zh) + '},');
  });
  out.push('    ]');
  out.push('  },');
});
out.push('};');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log('written, days:', days, 'all lines have zh:', ok);
