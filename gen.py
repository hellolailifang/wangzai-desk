import re as _re
def load_old_en(path):
    s = open(path, encoding='utf-8').read()
    p = s.index('EN_PRACTICE')
    start = s.index('{', p)
    depth=0; j=start; n=len(s)
    while j<n:
        c=s[j]
        if c=='{': depth+=1
        elif c=='}':
            depth-=1
            if depth==0:
                end=j+1; break
        j+=1
    return json.loads(s[start:end])

def brace_replace(text, key, items):
    m = _re.search(r'"%s"\s*:\s*\[' % _re.escape(key), text)
    if not m:
        raise SystemExit('key not found: '+key)
    i = m.end()-1
    depth=0; j=i; n=len(text)
    while j<n:
        c=text[j]
        if c=='"':
            j+=1
            while j<n:
                if text[j]=='\\':
                    j+=2; continue
                if text[j]=='"':
                    break
                j+=1
            j+=1; continue
        if c=='[':
            depth+=1
        elif c==']':
            depth-=1
            if depth==0:
                new=json.dumps(items, ensure_ascii=False, indent=2)
                return text[:i]+new+text[j+1:]
        j+=1
    raise SystemExit('unmatched [ for '+key)

