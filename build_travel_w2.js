let patched = 0;
travel.forEach(dest => {
  const extra = EXTRA.find(e => dest.title.includes(e.key));
  if (!extra) { console.log('⚠️  未匹配：' + dest.title); return; }

  // 表头对齐规范
  dest.blocks.forEach(b => {
    b.h = b.h.replace(/^🚉/, '✈️').replace(/^🥾/, '🗺');
  });

  // 去掉可能已存在的同名块，避免重复叠加（可重复执行）
  const newHeads = ['💰 价格预算（深圳出发）', '🍜 当地美食·吃什么', '⚠️ 安全与注意', '🎫 实操：许可 · 预约 · 证件'];
  dest.blocks = dest.blocks.filter(b => !newHeads.includes(b.h));

  const idxScenery = dest.blocks.findIndex(b => b.h.startsWith('🏞'));
  const priceBlock = { h: newHeads[0], body: '<p>' + extra.price + '</p>' };
  const foodBlock = { h: newHeads[1], body: '<p>' + extra.food + '</p>' };
  const warnBlock = { h: newHeads[2], body: '<p>' + extra.warn + '</p>' };
  const opsBlock = { h: newHeads[3], body: '<p>' + extra.ops + '</p>' };

  if (idxScenery >= 0) {
    // 价格插在景点前，美食/注意/实操接在景点后
    dest.blocks.splice(idxScenery, 0, priceBlock);
    dest.blocks.splice(idxScenery + 2, 0, foodBlock, warnBlock, opsBlock);
  } else {
    dest.blocks.push(priceBlock, foodBlock, warnBlock, opsBlock);
  }
  patched++;
});

