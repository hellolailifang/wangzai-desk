def pick_snack(budget):
    """从加餐库中挑 1–2 项：热量不超 budget 且尽量吃满，热量接近时优先蛋白高的。"""
    cands = [[i] for i in range(len(SNACKS))]
    cands += [[i, j] for i in range(len(SNACKS)) for j in range(i + 1, len(SNACKS))]
    ok = []
    for c in cands:
        kcal = sum(SNACKS[i][1] for i in c)
        if kcal <= budget:
            ok.append((kcal, sum(SNACKS[i][2] for i in c), c))
    if not ok:
        return [], 0
    max_kcal = max(o[0] for o in ok)
    # 在热量接近上限的组合里，挑蛋白最高的（热量差 30 以内视为同级）
    near = [o for o in ok if o[0] >= max_kcal - 30]
    near.sort(key=lambda o: (-o[1], -o[0]))
    return near[0][2], near[0][0]


