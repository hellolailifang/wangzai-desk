def js_to_json(text):
    """content.js 里顶层 key 与对象 key 均可能无引号，json.loads 解析不了，
    先用 node 把这段 JS 字面量转成 JSON 文本再解析。"""
    p = subprocess.run(
        [NODE, "-e", "const o=(" + text + ");process.stdout.write(JSON.stringify(o))"],
        capture_output=True, text=True)
    if p.returncode != 0:
        raise RuntimeError("node 解析失败: " + p.stderr[:2000])
    return p.stdout


