def find_array(src, key):
    """定位 geo: [ 或 "geo": [ 之后数组的 [ 与配对的 ]，跳过字符串内的括号
    （2026-10 起 content.js 顶层 key 改为无引号写法，两种都要兼容）"""
    m = re.search(r'(?m)^[ \t]*["\']?%s["\']?[ \t]*:[ \t]*\[' % re.escape(key), src)
    if not m:
        raise RuntimeError("未找到 key: " + key)
    i = m.end() - 1
    depth = 0
    j = i
    in_str = False
    esc = False
    q = ""
    while j < len(src):
        c = src[j]
        if in_str:
            if esc:
                esc = False
            elif c == "\\":
                esc = True
            elif c == q:
                in_str = False
        else:
            if c in ('"', "'"):
                in_str = True
                q = c
            elif c == "[":
                depth += 1
            elif c == "]":
                depth -= 1
                if depth == 0:
                    return i, j
        j += 1
    raise RuntimeError("未找到数组结尾: " + key)


