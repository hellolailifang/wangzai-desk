def find_card_end(text, start):
    """start 指向 <div class="co"> 之后，返回该卡片结束的 </div> 起始下标"""
    depth = 1
    i = start
    n = len(text)
    while i < n:
        io_ = text.find('<div', i)
        ic_ = text.find('</div>', i)
        if ic_ == -1:
            return n
        if io_ != -1 and io_ < ic_:
            depth += 1
            i = io_ + 4
        else:
            depth -= 1
            if depth == 0:
                return ic_
            i = ic_ + 6
    return n

card_pat = re.compile(r'<div class="co">')
name_pat = re.compile(r'<div class="co-h"><b>([^<]+)</b>')

out = []
last = 0
injected = 0
missing = []
for m in card_pat.finditer(text):
    start = m.end()
    end = find_card_end(text, start)
    card = text[start:end]
    nm = name_pat.search(card)
    if not nm:
        out.append(text[last:end])
        last = end
        continue
    name = nm.group(1).strip()
    if name in NARR:
        f, t = NARR[name]
        block = (f'\n<div class="co-r found"><b>📜 发家史：</b>{f}</div>'
                 f'\n<div class="co-r turn"><b>🔑 转折点：</b>{t}</div>')
        out.append(text[last:start] + card + block)
        injected += 1
    else:
        missing.append(name)
        out.append(text[last:end])
    last = end
out.append(text[last:])

new_text = ''.join(out)
open(SRC, 'w', encoding='utf-8').write(new_text)

